/** 给模型的知识库文本（≤ 2000 字）。 */
export function kbText() {
  return KB.map(([k, v]) => `【${k}】${v}`).join('\n').slice(0, 2000);
}

/** 这句话是不是在问鱼社怎么玩（规则判断，免得每句聊天都塞知识库费 token）。 */
export function asksAboutGame(text) {
  const s = String(text || '');
  const topic = /(零花钱|token|心情|精力|出门|冲浪|明信片|信箱|写信|相册|背包|图鉴|成长|长大|性格|人设|五维|智力|爱好|UP ?主|B ?站|睡觉|午睡|干活|上工|设置|鱼社|小贴士|怎么玩|玩法|规则)/i;
  const ask = /(怎么|如何|什么|啥|为什么|为啥|能不能|可以|会不会|吗|？|\?)/;
  return topic.test(s) && ask.test(s);
}
