/** 现在该出哪一条（没看过的里第一条满足条件的）。 */
export function nextTip(ctx, seen = []) {
  const s = new Set(seen);
  return TIPS.find((t) => !s.has(t.id) && safe(() => t.when(ctx))) || null;
}
const safe = (f) => { try { return Boolean(f()); } catch { return false; } };

